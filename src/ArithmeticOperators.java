public class ArithmeticOperators {
    public static void main(String[] args) {
        int num1 = 7;
        int num2 = 5;

        int result = num1 + num2;
        System.out.println(result);

        result = num1 - num2;
        System.out.println(result);

        result = num1 * num2;
        System.out.println(result);

        result = num1 / num2;
        System.out.println(result);

        result = num1 % num2;
        System.out.println(result);

        System.out.println("--------------");
        System.out.println(num1 += 2);
        System.out.println(num1 -= 1);
        System.out.println(num1 *= 2);
        System.out.println(num1 /= 2);
        System.out.println(num1++);
        System.out.println(num1--);
        // System.out.println();

    }
}
