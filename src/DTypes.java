public class DTypes {
    public static void main(String[] args) {
        // Integer types:
        int in = 10;
        byte by = 127;
        short sh = 558;
        long l = 5458l;

        // Decimal types:
        float marks = 6.5f;
        double d = 3.142857;

        // Character type:
        char c = 'k'; // NOT "K"

        // Boolean type:
        boolean b = true;

    }
}
